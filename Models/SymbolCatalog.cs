    // Every packaged symbol is offered.
    // Declared after All, because static fields are set up in the order they are written.
    public static IReadOnlyList<Symbol> Available { get; } = All;

    private static readonly HashSet<string> PackagedPictures = Available.Select(symbol => symbol.Asset).ToHashSet();

    /// <summary>
    /// The picture for an image name a tile saved. Each symbol is packed as one small WebP file
    /// (symbols/&lt;name&gt;.webp), not as an image at every screen size, so hundreds of them stay small.
    /// The app's own pictures are ordinary images found by name.
    /// </summary>
    public static ImageSource ImageFor(string asset)
    {
        if (PackagedPictures.Contains(asset))
        {
            return ImageSource.FromStream(_ => FileSystem.OpenAppPackageFileAsync($"symbols/{asset}.webp"));
        }

        return ImageSource.FromFile(asset);
    }
